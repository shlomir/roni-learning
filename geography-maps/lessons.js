/* [key, text] pairs for every narrated line – shared by the player and tools/gen-audio.mjs */
window.lessonLines = L => {
  const out = [];
  for (const [tid, les] of Object.entries(L)) {
    les.slides.forEach((s, i) => {
      const K = `L_${tid}_${i}`;
      if (s.t) out.push([K, s.t]);
      (s.items || []).forEach((it, j) => {
        const txt = it.say || it.t;
        if (txt) out.push([`${K}_${j}`, txt]);
        (it.lines || []).forEach((ln, k) => out.push([`${K}_${j}_${k}`, (it.says && it.says[k]) || ln]));
      });
    });
  }
  return out;
};
